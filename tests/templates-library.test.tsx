import React from 'react';
import {afterEach,it,expect} from 'vitest';
import {cleanup,render,screen,within} from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import {TemplatesLibrary,canonicalTemplateRoute} from '../apps/docs/src/templates-library';
afterEach(cleanup);
it.each([['patterns','templates'],['scene-styles','templates'],['templates','templates'],['templates/scenes','templates'],['scene/brand','scene/brand']])('normalizes %s without changing standalone scene routes',(input,result)=>{expect(canonicalTemplateRoute(input)).toBe(result);});
it('opens directly to scene templates and preserves scene switching and preview links',async()=>{
 const user=userEvent.setup();
 render(<TemplatesLibrary/>);
 expect(screen.getByRole('heading',{name:'样板库',level:1})).toBeVisible();
 expect(screen.getAllByRole('heading',{level:1})).toHaveLength(1);
 expect(screen.queryByRole('tablist',{name:'样板类型'})).not.toBeInTheDocument();
 expect(screen.queryByRole('tab',{name:'任务组合'})).not.toBeInTheDocument();
 expect(screen.getByRole('heading',{name:'噪声实时监测'})).toBeVisible();
 const sceneTabs=screen.getByRole('tablist',{name:'场景样板风格'});
 expect(within(sceneTabs).getAllByRole('tab')).toHaveLength(5);
 await user.click(within(sceneTabs).getByRole('tab',{name:/数据看板/}));
 expect(screen.getByRole('heading',{name:'测量质量概览'})).toBeVisible();
 expect(screen.getByRole('link',{name:'展开样板'})).toHaveAttribute('href','#scene/analytics');
 await user.click(within(sceneTabs).getByRole('tab',{name:/OpenTest 客户端/}));
 expect(screen.getByRole('region',{name:'OpenTest 客户端工作区'})).toBeVisible();
 expect(screen.getByRole('link',{name:'展开样板'})).toHaveAttribute('href','#scene/opentest');
 expect(within(sceneTabs).getAllByRole('tab').at(-1)).toHaveTextContent('品牌空白页');
 await user.click(within(sceneTabs).getByRole('tab',{name:/测量工作台/}));
 expect(screen.getByRole('heading',{name:'噪声实时监测'})).toBeVisible();
 expect(screen.getByRole('link',{name:'展开样板'})).toHaveAttribute('href','#scene/precision');
 expect(screen.getByRole('link',{name:'返回样板库'})).toHaveAttribute('href','#templates');
});
it('opens the branded blank page and switches appearance and title with native controls',async()=>{
 const user=userEvent.setup();
 const {container}=render(<TemplatesLibrary/>);
 await user.click(screen.getByRole('tab',{name:/品牌空白页/}));
 expect(screen.getByRole('link',{name:'展开样板'})).toHaveAttribute('href','#scene/blank');
 const page=screen.getByRole('region',{name:'CRYSOUND 品牌空白页'});
 expect(page).toHaveAttribute('data-appearance','light');
 expect(within(page).getByRole('heading',{name:'让声音被看见',level:2})).toBeVisible();
 const colors=screen.getByRole('group',{name:'空白页配色'});
 const dark=within(colors).getByRole('button',{name:'深色'});
 dark.focus();
 await user.keyboard(' ');
 expect(page).toHaveAttribute('data-appearance','dark');
 expect(dark).toHaveAttribute('aria-pressed','true');
 expect(within(page).getByRole('img',{name:'CRYSOUND'})).toHaveAttribute('src','/brand/logo-horizontal-white.svg');
 expect(container.querySelector('.brand-blank-wave')).toHaveAttribute('src','/brand/blank-wave-dark.png');
 await user.click(screen.getByRole('switch',{name:'显示标题'}));
 expect(within(page).queryByText('让声音被看见')).not.toBeInTheDocument();
 expect(within(page).getByRole('heading',{name:'品牌空白页'})).toBeInTheDocument();
 expect(within(page).getByRole('img',{name:'CRYSOUND'})).toBeVisible();
 await user.click(within(colors).getByRole('button',{name:'浅色'}));
 expect(page).toHaveAttribute('data-appearance','light');
 expect(within(page).getByRole('img',{name:'CRYSOUND'})).toHaveAttribute('src','/brand/logo-horizontal-purple.svg');
});
