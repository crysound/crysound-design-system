import React from 'react';
import {afterAll,afterEach,beforeAll,expect,it,vi} from 'vitest';
import {act,cleanup,fireEvent,render,screen} from '@testing-library/react';
import {Carousel,type CarouselProps} from '../packages/ui/src/carousel';

class TestPointerEvent extends MouseEvent {
 readonly pointerId:number;readonly isPrimary:boolean;
 constructor(type:string,init:PointerEventInit={}){super(type,init);this.pointerId=init.pointerId??1;this.isPrimary=init.isPrimary??true;}
}
beforeAll(()=>vi.stubGlobal('PointerEvent',TestPointerEvent));
afterAll(()=>vi.unstubAllGlobals());
afterEach(()=>{cleanup();vi.restoreAllMocks();});
function setup(props:Partial<CarouselProps>={}){
 const open=vi.fn();const items=[
  {id:'a',label:'文章一',content:<><a href="/article" onClick={event=>{event.preventDefault();open();}}>阅读全文</a><input aria-label="备注"/><button>卡片操作</button></>},
  {id:'b',label:'文章二',content:<img src="/b.png" alt="第二张图"/>},
  {id:'c',label:'文章三',content:'第三张内容'},
 ];
 const view=render(<Carousel items={items} label="文章" draggable loop={false} {...props}/>);
 const viewport=view.container.querySelector<HTMLDivElement>('.cs-carousel-viewport')!;
 // The template scales a 1000px canvas to 600px on screen.
 vi.spyOn(viewport,'getBoundingClientRect').mockReturnValue({x:0,y:0,left:0,top:0,right:600,bottom:300,width:600,height:300,toJSON:()=>({})});
 Object.defineProperty(viewport,'clientWidth',{value:1000});
 vi.spyOn(viewport,'hasPointerCapture').mockReturnValue(true);
 const pointer=(type:string,x:number,y=40,time=0,target:Element=viewport)=>{
  const event=new TestPointerEvent(type,{bubbles:true,cancelable:true,pointerId:1,clientX:x,clientY:y,button:0});
  Object.defineProperty(event,'timeStamp',{value:time});fireEvent(target,event);return event;
 };
 return {...view,viewport,pointer,open,track:view.container.querySelector('.cs-carousel-track')!};
}
it('tracks the mouse inside a scaled preview and selects a single next group on release',()=>{
 const {pointer,track,viewport}=setup();const capture=vi.spyOn(viewport,'setPointerCapture');
 pointer('pointerdown',400);pointer('pointermove',280,40,200);
 expect(track).toHaveStyle({transform:'translate3d(-20%,0,0)'});expect(capture).toHaveBeenCalledWith(1);
 pointer('pointerup',280,40,320);
 expect(screen.getByRole('group',{name:'2 / 3 · 文章二'})).toBeVisible();
 expect(screen.getByRole('button',{name:'文章二'})).toHaveAttribute('aria-current','true');
 expect(track).toHaveStyle({transform:'translate3d(-100%,0,0)'});
});
it('suppresses the click generated by dragging a link while preserving a short normal click',()=>{
 const {pointer,open}=setup();const link=screen.getByRole('link',{name:'阅读全文'});
 pointer('pointerdown',400,40,0,link);pointer('pointermove',280,40,200);pointer('pointerup',280,40,320);
 fireEvent.click(link,{detail:1});expect(open).not.toHaveBeenCalled();
 fireEvent.click(screen.getByRole('button',{name:'文章一'}));
 pointer('pointerdown',400,40,500,link);pointer('pointermove',396,40,600);pointer('pointerup',396,40,700);
 fireEvent.click(link,{detail:1});expect(open).toHaveBeenCalledOnce();
});
it('allows vertical page gestures and cancels interrupted horizontal drags',()=>{
 const {pointer,track}=setup();pointer('pointerdown',400);
 expect(pointer('pointermove',396,100,200).defaultPrevented).toBe(false);
 pointer('pointerup',396,100,300);expect(track).toHaveStyle({transform:'translate3d(0%,0,0)'});
 pointer('pointerdown',400,40,500);pointer('pointermove',280,40,700);pointer('pointercancel',280,40,800);
 expect(screen.getByRole('group',{name:'1 / 3 · 文章一'})).toBeVisible();expect(track).toHaveStyle({transform:'translate3d(0%,0,0)'});
});
it.each([{index:0,from:300,to:420},{index:2,from:300,to:180}])('resists dragging past boundary $index without wrapping',({index,from,to})=>{
 const {pointer,track}=setup({defaultValue:index});pointer('pointerdown',from);pointer('pointermove',to,40,200);pointer('pointerup',to,40,320);
 expect(track).toHaveStyle({transform:`translate3d(${-index*100}%,0,0)`});
 expect(screen.getByRole('button',{name:index===0?'文章一':'文章三'})).toHaveAttribute('aria-current','true');
});
it('does not steal dragging or clicks from embedded form controls',()=>{
 const {pointer,track}=setup();const input=screen.getByRole('textbox',{name:'备注'});
 pointer('pointerdown',400,40,0,input);pointer('pointermove',200,40,200);pointer('pointerup',200,40,320);
 expect(track).toHaveStyle({transform:'translate3d(0%,0,0)'});
 fireEvent.change(input,{target:{value:'仍可编辑'}});expect(input).toHaveValue('仍可编辑');
});
it('holds the dragged frame until the requested image is ready',async()=>{
 const {pointer,track,container}=setup();const image=container.querySelector('img')!;
 Object.defineProperty(image,'complete',{value:false});let decoded!:()=>void;
 Object.defineProperty(image,'decode',{value:()=>new Promise<void>(resolve=>{decoded=resolve;})});
 pointer('pointerdown',400);pointer('pointermove',280,40,200);pointer('pointerup',280,40,320);
 expect(screen.getByRole('link',{name:'阅读全文'})).toBeVisible();expect(track).toHaveStyle({transform:'translate3d(-20%,0,0)'});
 fireEvent.load(image);await act(async()=>{decoded();});
 expect(screen.getByRole('img',{name:'第二张图'})).toBe(image);expect(track).toHaveStyle({transform:'translate3d(-100%,0,0)'});
});
it('retains controlled ownership and keyboard navigation after a gesture',()=>{
 const onValueChange=vi.fn();const {pointer,track}=setup({value:0,onValueChange});
 pointer('pointerdown',400);pointer('pointermove',280,40,200);pointer('pointerup',280,40,320);
 expect(onValueChange).toHaveBeenLastCalledWith(1);expect(track).toHaveStyle({transform:'translate3d(0%,0,0)'});
 fireEvent.keyDown(screen.getByRole('region',{name:'文章'}),{key:'ArrowRight'});expect(onValueChange).toHaveBeenCalledTimes(2);
});
